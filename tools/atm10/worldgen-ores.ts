/** Mod ores in new chunks (docs/atm10-port.md, "Worldgen in the full pack"): a world with carries of ore mods, the
 * player sent to chunks no one has generated yet, and the blocks of four of those chunks counted once they load.
 * Every listed mod must have ore blocks there: All the Ores' and Modern Industrialization's by default, which the
 * carries generate through their own biome modifiers and features in 26.3's form.
 *
 *   ATM10_CARRIES=<carries> bun run tools/atm10/worldgen-ores.ts
 *
 * - ATM10_CARRIES: the carries folder `final-data` wrote.
 * - WORLDGEN_ORES_MODS: comma-separated carries to load and expect ores of (default
 *   `alltheores,modern_industrialization`). */
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const { WorldFixture, until } = await import('../../ae2/tests/world/harness');
const carries = resolve(process.env.ATM10_CARRIES ?? '');
assert(process.env.ATM10_CARRIES && existsSync(carries), 'ATM10_CARRIES names the carries folder');
const mods = (process.env.WORLDGEN_ORES_MODS ?? 'alltheores,modern_industrialization').split(',').map(s => s.trim()).filter(Boolean);
for (const id of mods) assert(existsSync(join(carries, id, 'horizon-mod.toml')), `ATM10_CARRIES has the ${id} carry`);
process.env.AE2_TEST_STARTUP_MS = String(Math.max(Number(process.env.AE2_TEST_STARTUP_MS ?? 0), 900_000));

/** The ids mods and vanilla give their ores (horizon_client::worldgen_audit::is_ore). */
const isOre = (id: string) => {
  const path = id.split(':')[1] ?? id;
  return path.endsWith('_ore') || path.includes('_ore_') || path.startsWith('ore_') || path === 'ore';
};
const fixture = new WorldFixture('worldgen-ores', 'server-thread', { devMods: mods.map(id => join(carries, id)) });
const loaded = async (x: number, z: number) =>
  ((await fixture.command(`execute if loaded ${x} 0 ${z}`)).chat ?? []).includes('Test passed');
try {
  const spawn = await fixture.start();
  const [px, , pz] = spawn.player.position;
  // Far from spawn, so nothing there was generated with the world: the chunk is not loaded before the player goes.
  const [x, z] = [Math.floor(px / 16) * 16 + 16 * 300, Math.floor(pz / 16) * 16 + 16 * 300];
  assert(!(await loaded(x, z)), `chunk at ${x} ${z} not generated before the player goes there`);
  await fixture.command('gamemode spectator');
  await fixture.command(`tp @s ${x + 8} 100 ${z + 8}`);
  // The four chunks from (x, z): generated by the server, then sent to the window's world.
  const chunks = [[0, 0], [16, 0], [0, 16], [16, 16]].map(([dx, dz]) => [x + dx, z + dz]);
  for (const [cx, cz] of chunks) await until(() => loaded(cx, cz), ok => ok, `chunk ${cx} ${cz} generated`, 120_000);
  fixture.mark(`4 new chunks generated at ${x} ${z}`);
  const ores: Record<string, Record<string, number>> = {};
  for (const [cx, cz] of chunks) {
    // y -64..63: 16 x 16 x 128 = the command's 32768 blocks at most. Waited for until the window has the chunk's stone.
    const reply = await until(() => fixture.raw(`blocks ${cx} -64 ${cz} ${cx + 15} 63 ${cz + 15}`, 120_000),
      r => Object.values(r.counts ?? {}).reduce((a: number, b: any) => a + Number(b), 0) > 16 * 16 * 64,
      `chunk ${cx} ${cz} in the window`, 120_000);
    for (const [id, n] of Object.entries(reply.counts as Record<string, number>)) {
      if (!isOre(id)) continue;
      const ns = id.split(':')[0];
      (ores[ns] ??= {})[id] = (ores[ns][id] ?? 0) + n;
    }
  }
  const total = (ns: string) => Object.values(ores[ns] ?? {}).reduce((a, b) => a + b, 0);
  console.log(`ores in 4 new chunks: ${Object.keys(ores).sort().map(ns => `${ns} ${total(ns)}`).join(', ')}`);
  for (const ns of Object.keys(ores).sort()) {
    console.log(`  ${ns}: ${Object.entries(ores[ns]).sort((a, b) => b[1] - a[1]).map(([id, n]) => `${id} ${n}`).join(', ')}`);
  }
  for (const id of mods) {
    assert(total(id) > 0, `${id} ores in the new chunks`);
    fixture.mark(`${id}: ${total(id)} ore blocks of ${Object.keys(ores[id]).length} kinds in 4 new chunks`);
  }
  fixture.report('passed');
} catch (error) {
  fixture.report('failed', error);
  throw error;
} finally {
  await fixture.close();
}
